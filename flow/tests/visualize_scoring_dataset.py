from graspnetAPI import GraspGroup
from utils.arguments import cfgs


def make_open3d_cloud(points, colors=None):
    """Build an Open3D point cloud from numpy point and color arrays."""
    cloud = o3d.geometry.PointCloud()
    cloud.points = o3d.utility.Vector3dVector(points.astype(np.float64))
    if colors is not None:
        cloud.colors = o3d.utility.Vector3dVector(colors.astype(np.float64))
    return cloud


def graspgroup_from_scoring_label(rot_lie, width, depth, score, seed_xyz):
    """Convert one scoring-dataset 5D label into a GraspNetAPI GraspGroup."""
    rot_flat = exp_so3(rot_lie.reshape(1, 3)).reshape(1, 9).cpu()
    score = score.reshape(1, 1).cpu()
    grasp_width = torch.clamp(width.reshape(1, 1).cpu(), min=0.0, max=0.1)
    grasp_depth = torch.clamp(depth.reshape(1, 1).cpu(), min=0.01, max=0.04)
    grasp_height = 0.02 * torch.ones_like(score)
    translation = seed_xyz.reshape(1, 3).cpu()
    obj_ids = -1 * torch.ones_like(score)

    grasp_array = torch.cat(
        [
            score,
            grasp_width,
            grasp_height,
            grasp_depth,
            rot_flat,
            translation,
            obj_ids,
        ],
        dim=-1,
    ).numpy()
    return GraspGroup(grasp_array)


def resolve_dataset_index(dataset, scene_name, frame_id):
    """Find the GraspNetDataset index for a generated sample scene/frame."""
    for idx, (candidate_scene, candidate_frame) in enumerate(zip(dataset.scenename, dataset.frameid)):
        if candidate_scene == scene_name and int(candidate_frame) == int(frame_id):
            return idx
    raise ValueError(f"Could not find {scene_name} frame {frame_id} in split {dataset.split}.")


def select_score_one_slot(sample, atol):
    """Select the first seed/view slot whose generated score is 1.0."""
    scores = unpack_score(sample).squeeze(0)  # [N, 300]
    valid_mask = sample['seed_valid_mask'].squeeze(0).bool()  # [N]
    score_one_mask = torch.isclose(scores, torch.ones_like(scores), atol=atol)
    score_one_mask = score_one_mask & valid_mask.unsqueeze(1)
    if not score_one_mask.any():
        max_score = float(scores[valid_mask].max().item()) if valid_mask.any() else float(scores.max().item())
        raise ValueError(f"No valid score==1.0 slot found. Max score in sample is {max_score:.6f}.")

    seed_idx, view_idx = torch.nonzero(score_one_mask, as_tuple=False)[0].tolist()
    return int(seed_idx), int(view_idx)


def unpack_score(sample):
    """Return scoring labels as float scores in [0, 1]."""
    if 'seed_grasp_score_uint8' in sample:
        return sample['seed_grasp_score_uint8'].float() / 10.0
    return sample['seed_grasp_score'].float()


def unpack_width(sample):
    """Return scoring width labels as float meters."""
    if 'seed_grasp_width_uint8' in sample:
        return sample['seed_grasp_width_uint8'].float() / 1000.0
    return sample['seed_grasp_width'].float()


def unpack_depth(sample):
    """Return scoring depth labels as float meters."""
    if 'seed_grasp_depth_uint8' in sample:
        return 0.01 + sample['seed_grasp_depth_uint8'].float() * 0.01
    return sample['seed_grasp_depth'].float()


def main():
    """Visualize one score-1.0 grasp generated by generate_scoring_dataset.py."""
    parser = argparse.ArgumentParser(description="Visualize one score-1.0 grasp from a scoring dataset sample.")
    parser.add_argument('--sample_path', type=str,
                        default='/tmp/scoring_dataset_one_frame/train/sample_000000.pt',
                        help='Path to a .pt sample generated by generate_scoring_dataset.py.')
    parser.add_argument('--dataset_root', type=str, default='/media/dsp520/Grasp_2T/graspnet',
                        help='GraspNet dataset root.')
    parser.add_argument('--split', type=str, default='train',
                        choices=['train', 'eval', 'test', 'test_seen', 'test_similar', 'test_novel'],
                        help='Split that contains the generated sample scene.')
    parser.add_argument('--camera', type=str, default='realsense', choices=['realsense', 'kinect'],
                        help='Camera split used when the sample was generated.')
    parser.add_argument('--score_atol', type=float, default=1e-6,
                        help='Tolerance used when matching score == 1.0.')
    parser.add_argument('--seed_idx', type=int, default=None,
                        help='Optional seed index override.')
    parser.add_argument('--view_idx', type=int, default=None,
                        help='Optional 300-view slot index override.')
    parser.add_argument('--smoke_test', action='store_true',
                        help='Prepare geometry and print selected grasp metadata without opening Open3D.')
    args = parser.parse_args()

    sample = torch.load(args.sample_path, map_location='cpu', weights_only=True)
    scene_name = sample['scene_name']
    frame_id = int(sample['frame_id'])

    if args.seed_idx is None or args.view_idx is None:
        seed_idx, view_idx = select_score_one_slot(sample, args.score_atol)
    else:
        seed_idx, view_idx = args.seed_idx, args.view_idx

    seed_xyz = sample['xyz_graspable'].squeeze(0).float()  # [N, 3]
    rot_lie = sample['seed_grasp_rot_lie'].squeeze(0).float()  # [N, 300, 3]
    width = unpack_width(sample).squeeze(0)  # [N, 300]
    depth = unpack_depth(sample).squeeze(0)  # [N, 300]
    score = unpack_score(sample).squeeze(0)  # [N, 300]
    valid_mask = sample['seed_valid_mask'].squeeze(0).bool()  # [N]

    if not valid_mask[seed_idx]:
        raise ValueError(f"Selected seed {seed_idx} is invalid in seed_valid_mask.")

    selected_score = score[seed_idx, view_idx]
    selected_width = width[seed_idx, view_idx]
    selected_depth = depth[seed_idx, view_idx]
    selected_seed_xyz = seed_xyz[seed_idx]
    selected_rot_lie = rot_lie[seed_idx, view_idx]

    dataset = GraspNetDataset(
        args.dataset_root,
        camera=args.camera,
        split=args.split,
        num_points=cfgs.num_point,
        remove_outlier=True,
        augment=False,
        load_label=False,
    )
    data_idx = resolve_dataset_index(dataset, scene_name, frame_id)
    cloud_points, cloud_colors = dataset.get_data(data_idx, return_raw_cloud=True)
    cloud = make_open3d_cloud(cloud_points, cloud_colors)

    grasp_group = graspgroup_from_scoring_label(
        selected_rot_lie,
        selected_width,
        selected_depth,
        selected_score,
        selected_seed_xyz,
    )
    grasp_geoms = grasp_group.to_open3d_geometry_list()
    for geom in grasp_geoms:
        geom.paint_uniform_color([0.0, 0.35, 1.0])

    seed_marker = o3d.geometry.TriangleMesh.create_sphere(radius=0.004)
    seed_marker.translate(selected_seed_xyz.numpy())
    seed_marker.paint_uniform_color([0.0, 1.0, 0.0])

    print(
        "Selected scoring grasp: "
        f"sample={args.sample_path}, scene={scene_name}, frame={frame_id}, "
        f"dataset_idx={data_idx}, seed_idx={seed_idx}, view_idx={view_idx}, "
        f"score={float(selected_score.item()):.6f}, "
        f"width={float(selected_width.item()):.6f}, "
        f"depth={float(selected_depth.item()):.6f}, "
        f"seed_xyz={selected_seed_xyz.tolist()}",
        flush=True,
    )
    print(
        f"Sample stats: valid_seeds={int(valid_mask.sum().item())}/{valid_mask.numel()}, "
        f"score_one_slots={int(torch.isclose(score, torch.ones_like(score), atol=args.score_atol).sum().item())}",
        flush=True,
    )

    if args.smoke_test:
        print("Smoke test done. Geometry was prepared but Open3D window was skipped.", flush=True)
        return

    o3d.visualization.draw_geometries(
        [cloud, seed_marker] + grasp_geoms,
        window_name=f"Scoring label score=1.0 - {scene_name} frame {frame_id}",
    )


if __name__ == '__main__':
    main()
