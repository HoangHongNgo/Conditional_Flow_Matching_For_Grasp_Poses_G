import os
import sys

import numpy as np
import open3d as o3d
import torch

# Add workspace root to sys.path.
sys.path.append(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))

from dataset.graspnet_dataset import GraspNetDataset
